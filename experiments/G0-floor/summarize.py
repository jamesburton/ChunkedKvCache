"""G0 numerical floor: summary tables from the `ChunkKvLab floor` CSVs.

usage: uv run summarize.py [<dir with floor-*.csv, contexts-*.csv, tasks-*.csv, timing-*.csv>]   (default: this directory)
writes summary.md and tolerance.csv next to this script. Standard library only.

Definitions (README, "What was measured"):
- per-layer floor = pooled over every context row of every context: mean and nearest-rank p99 of the per-row relative L2
  ||dX_row|| / ||X_ref,row|| (X = K or V); taken from floor-<size>.csv (computed in C# over the raw rows).
- band value: mean of the per-layer means over the band's layers; band p99 = the largest per-layer p99 in the band.
- 95 % intervals: percentile bootstrap over contexts (cluster = context, 2,000 resamples, seed 0) of the pooled statistic,
  rebuilt from the per-context n / mean rows (contexts-<size>.csv) or per-task rows (tasks-<size>.csv).
"""
import csv
import gzip
import random
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE
E4 = HERE.parent / 'E4-structure-aware' / 'results.csv.gz'
BANDS = [('0', [0]), ('1', [1]), ('2-3', [2, 3]), ('4-11', list(range(4, 12))), ('12-23', list(range(12, 24))),
         ('24-35', list(range(24, 36)))]
B = 2000


def read(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def boot(units, stat, seed=0):
    """Percentile 95 % interval of stat(sample) over resampled units (clusters)."""
    rng = random.Random(seed)
    vals = sorted(stat([units[rng.randrange(len(units))] for _ in units]) for _ in range(B))
    return vals[int(0.025 * B)], vals[int(0.975 * B) - 1]


def pooled_mean(sample):
    n = sum(u[0] for u in sample)
    return sum(u[1] for u in sample) / n if n else float('nan')


def fmt(x, digits=2):
    if x != x:
        return 'n/a'
    if x == 0:
        return '0'
    return f'{x:.{digits}e}' if abs(x) < 1e-2 or abs(x) >= 1e3 else f'{x:.{max(digits, 3)}f}'.rstrip('0').rstrip('.')


def pair_order(p):
    return ({'a': 0, 'b': 1, 'c': 2}[p[0]], -int(p.split('_vk')[-1]) if p.startswith('b_') else 0)


def main():
    labels = sorted({p.stem.split('-', 1)[1] for p in SRC.glob('floor-*.csv')}, key=lambda s: (int(s.split('k')[0]), s))
    out = ['# G0 floor: summary tables', '',
           'Generated by `summarize.py` from `floor-*.csv`, `contexts-*.csv`, `tasks-*.csv`, `timing-*.csv`. Relative L2 per row is',
           '‖ΔX_row‖ / ‖X_ref,row‖; per-layer values are pooled over every row of every context. Band = mean of the per-layer means;',
           'band p99 = largest per-layer p99 in the band. Intervals: 95 % percentile bootstrap over contexts (2,000 resamples).', '']
    tol = []
    for label in labels:
        floor = read(SRC / f'floor-{label}.csv')
        ctx = read(SRC / f'contexts-{label}.csv')
        tasks = read(SRC / f'tasks-{label}.csv')
        timing = read(SRC / f'timing-{label}.csv')
        pairs = sorted({r['pair'] for r in floor}, key=pair_order)
        nctx = len({r['context_id'] for r in ctx})
        layer = {(r['pair'], int(r['layer']), r['kind']): r for r in floor if r['kind'] in ('K', 'V')}
        logits = {r['pair']: r for r in floor if r['kind'] == 'logits'}
        out += [f'## {label} ({nctx} contexts, {len(tasks) // max(1, len(pairs))} tasks, '
                f'{sum(int(r["n"]) for r in floor if r["pair"] == pairs[0] and r["layer"] == "0" and r["kind"] == "K")} context rows)', '']

        # ---- K / V by band ------------------------------------------------------------------------------------------
        for kind in ('K', 'V'):
            out += [f'### {kind}: relative L2 per row, band mean / band p99', '',
                    '| pair | ' + ' | '.join(f'L{b}' for b, _ in BANDS) + ' | worst layer mean | worst layer p99 | max row |',
                    '|---|' + '---|' * (len(BANDS) + 3)]
            for p in pairs:
                cells = []
                for _, ls in BANDS:
                    m = sum(float(layer[(p, l, kind)]['rel_l2_mean']) for l in ls) / len(ls)
                    q = max(float(layer[(p, l, kind)]['rel_l2_p99']) for l in ls)
                    cells.append(f'{fmt(m)} / {fmt(q)}')
                wm = max(range(36), key=lambda l: float(layer[(p, l, kind)]['rel_l2_mean']))
                wq = max(range(36), key=lambda l: float(layer[(p, l, kind)]['rel_l2_p99']))
                mx = max(float(layer[(p, l, kind)]['rel_l2_max']) for l in range(36))
                out.append(f'| {p} | ' + ' | '.join(cells)
                           + f' | {fmt(float(layer[(p, wm, kind)]["rel_l2_mean"]))} (L{wm}) | {fmt(float(layer[(p, wq, kind)]["rel_l2_p99"]))} (L{wq}) | {fmt(mx)} |')
            out.append('')

        # ---- all-layer mean with context bootstrap and spread ----------------------------------------------------------
        out += ['### All-layer mean relative L2 (mean of the 36 per-layer pooled means) with 95 % CI over contexts, and per-context spread', '',
                '| pair | K mean [95 % CI] | V mean [95 % CI] | K: per-context min / median / max | K: max context / pooled | V: max context / pooled |',
                '|---|---|---|---|---|---|']
        byctx = defaultdict(lambda: defaultdict(dict))  # pair -> context -> (layer, kind) -> (n, sum)
        for r in ctx:
            byctx[r['pair']][r['context_id']][(int(r['layer']), r['kind'])] = (int(r['n']), int(r['n']) * float(r['rel_l2_mean']))
        for p in pairs:
            units = list(byctx[p].values())
            row = [p]
            spread = {}
            for kind in ('K', 'V'):
                def stat(sample, kind=kind):
                    return sum(pooled_mean([u[(l, kind)] for u in sample]) for l in range(36)) / 36
                point = stat(units)
                lo, hi = boot(units, stat)
                row.append(f'{fmt(point)} [{fmt(lo)}, {fmt(hi)}]')
                per = sorted(stat([u]) for u in units)
                spread[kind] = (per, point)
            per, point = spread['K']
            row.append(f'{fmt(per[0])} / {fmt(per[len(per) // 2])} / {fmt(per[-1])}')
            row.append(f'{per[-1] / point:.2f}' if point else 'n/a')
            perv, pointv = spread['V']
            row.append(f'{perv[-1] / pointv:.2f}' if pointv else 'n/a')
            out.append('| ' + ' | '.join(row) + ' |')
            tol.append(dict(size=label, pair=p, metric='kv_all_layer_mean_K', floor=point,
                            max_context_ratio=per[-1] / point if point else float('nan')))
            tol.append(dict(size=label, pair=p, metric='kv_all_layer_mean_V', floor=pointv,
                            max_context_ratio=perv[-1] / pointv if pointv else float('nan')))
        out.append('')

        # ---- per-layer single-context spread (what single-context tolerances must absorb) ------------------------------
        out += ['### Per-layer single-context spread: worst (context, layer) value / pooled per-layer value', '',
                '| pair | mean K | mean V | p99 K | p99 V | contexts with a layer p99 > 1.5x pooled |', '|---|---|---|---|---|---|']
        for p in pairs:
            if p.startswith('c_'):
                continue
            worst = {}
            failing = set()
            for r in ctx:
                if r['pair'] != p:
                    continue
                f = layer[(p, int(r['layer']), r['kind'])]
                for stat in ('mean', 'p99'):
                    ref = float(f[f'rel_l2_{stat}'])
                    ratio = float(r[f'rel_l2_{stat}']) / ref if ref else float('nan')
                    key = (stat, r['kind'])
                    if ratio == ratio and ratio > worst.get(key, (0, ''))[0]:
                        worst[key] = (ratio, r['layer'])
                    if stat == 'p99' and ratio > 1.5:
                        failing.add(r['context_id'])
            cells = [f'{worst[(s, k)][0]:.2f} (L{worst[(s, k)][1]})' for s in ('mean', 'p99') for k in ('K', 'V')]
            out.append(f'| {p} | ' + ' | '.join(cells) + f' | {len(failing)} / {nctx} |')
            for s in ('mean', 'p99'):
                for k in ('K', 'V'):
                    tol.append(dict(size=label, pair=p, metric=f'kv_layer_{s}_{k}_single_context_worst_ratio',
                                    floor=float('nan'), max_context_ratio=worst[(s, k)][0]))
        out.append('')

        # ---- logits ---------------------------------------------------------------------------------------------------
        out += ['### Logits on the teacher-forced E4 evaluation blocks (32 continuation rows per task)', '',
                '| pair | KL mean [95 % CI] (nats) | KL p99 | KL max | top-1 agreement | max task KL mean / pooled | abs Δ mask NLL mean / max | mask EM agreement |',
                '|---|---|---|---|---|---|---|---|']
        bytask = defaultdict(lambda: defaultdict(list))
        for r in tasks:
            bytask[r['pair']][r['context_id']].append((int(r['rows']), int(r['rows']) * float(r['kl_mean'])))
        for p in pairs:
            g = logits[p]
            units = [(sum(n for n, _ in v), sum(s for _, s in v)) for v in bytask[p].values()]
            point = pooled_mean(units)
            lo, hi = boot(units, pooled_mean)
            per_task = [float(r['kl_mean']) for r in tasks if r['pair'] == p]
            ratio = max(per_task) / point if point else float('nan')
            out.append(f'| {p} | {fmt(point)} [{fmt(lo)}, {fmt(hi)}] | {fmt(float(g["kl_p99"]))} | {fmt(float(g["kl_max"]))} | '
                       f'{float(g["top1"]):.4f} | {fmt(ratio) if ratio == ratio else "n/a"} | {fmt(float(g["mask_nll_absdiff_mean"]))} / '
                       f'{fmt(float(g["mask_nll_absdiff_max"]))} | {float(g["mask_em_agree"]):.3f} |')
            tol.append(dict(size=label, pair=p, metric='kl_mean', floor=point, max_context_ratio=ratio))
            tol.append(dict(size=label, pair=p, metric='top1', floor=float(g['top1']), max_context_ratio=float('nan')))
            tol.append(dict(size=label, pair=p, metric='mask_nll_absdiff_mean', floor=float(g['mask_nll_absdiff_mean']),
                            max_context_ratio=float(g['mask_nll_absdiff_max']) / float(g['mask_nll_absdiff_mean'])
                            if float(g['mask_nll_absdiff_mean']) else float('nan')))
        out.append('')

        # ---- timing ---------------------------------------------------------------------------------------------------
        arms = defaultdict(list)
        for r in timing:
            arms[(r['arm'], int(r['block']))].append((float(r['prefill_ms']), int(r['context_tokens'])))
        out += ['### Prefill time (ms, mean over contexts; first context includes warm-up)', '', '| arm | block | mean ms | tokens/s |', '|---|---|---|---|']
        for (arm, block), v in sorted(arms.items(), key=lambda kv: (kv[0][0].startswith('cpu'), -kv[0][1], kv[0][0])):
            ms = sum(x for x, _ in v) / len(v)
            tps = sum(t for _, t in v) / (sum(x for x, _ in v) / 1000)
            out.append(f'| {arm} | {block} | {ms:.0f} | {tps:.0f} |')
        out.append('')

        # ---- E4 comparison (2K kept contexts only) --------------------------------------------------------------------
        if E4.exists() and any(r['context_id'].endswith('/kept/p0') for r in tasks):
            out += e4_section(tasks, pairs)

    with open(HERE / 'tolerance.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=['size', 'pair', 'metric', 'floor', 'max_context_ratio'])
        w.writeheader()
        for t in tol:
            w.writerow({k: (f'{v:.6g}' if isinstance(v, float) else v) for k, v in t.items()})
    (HERE / 'summary.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'wrote summary.md and tolerance.csv ({", ".join(labels)})')


def e4_section(tasks, pairs):
    e4 = defaultdict(dict)
    with gzip.open(E4, 'rt', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['chunker'] == 'symbol' and r['seed'] == '0' and r['mode'] == 'kept':
                e4[(r['corpus'], r['plan'], r['task_id'])][(r['arm'], round(float(r['budget_pct'])))] = r
    out = ['### Against E4 (2K, symbol / seed 0 kept contexts shared with E4)', '']
    a = next(p for p in pairs if p.startswith('a_'))
    rows = [r for r in tasks if r['pair'] == a and (r['corpus'], r['plan'], r['task_id']) in e4]
    if not rows:
        return out + ['No shared tasks.', '']
    dev = max(abs(float(r['ref_mask_nll']) - float(e4[(r['corpus'], r['plan'], r['task_id'])][('full', 100)]['mask_nll'])) for r in rows)
    out.append(f'- **Reproduction:** {len(rows)} tasks in {len({r["context_id"] for r in rows})} contexts are E4 instances; this run\'s CPU '
               f'full-prefill masked-call NLL equals E4\'s `full` row within {dev:.1e} (E4 prints 6 significant digits).')
    gaps, diffs = [], defaultdict(list)
    for r in rows:
        k = (r['corpus'], r['plan'], r['task_id'])
        gaps.append(float(e4[k][('naive', 0)]['mask_nll']) - float(e4[k][('full', 100)]['mask_nll']))
    for p in pairs:
        for r in tasks:
            k = (r['corpus'], r['plan'], r['task_id'])
            if r['pair'] == p and k in e4:
                diffs[p].append(abs(float(r['mask_nll']) - float(r['ref_mask_nll'])))
    mg = sum(gaps) / len(gaps)
    out.append(f'- **Naive→full masked-call NLL gap** on these tasks (E4, CPU): mean {mg:.3f} nats (min {min(gaps):.3f}, max {max(gaps):.3f}).')
    out += ['', '| pair | mean abs Δ mask NLL | as a share of the mean gap | max over tasks of abs Δ / own gap |', '|---|---|---|---|']
    for p in pairs:
        ratios = [d / g for d, g in zip(diffs[p], gaps) if g > 0]
        out.append(f'| {p} | {sum(diffs[p]) / len(diffs[p]):.4f} | {sum(diffs[p]) / len(diffs[p]) / mg:.3f} | {max(ratios):.3f} |')
    # E4 secondary KL on the same tasks.
    def kl(arm, pct):
        v = [float(e4[(r['corpus'], r['plan'], r['task_id'])][(arm, pct)]['kl_cont']) for r in rows
             if (arm, pct) in e4[(r['corpus'], r['plan'], r['task_id'])]]
        return (sum(v) / len(v), len(v)) if v else (float('nan'), 0)
    out += ['', 'E4 post-query KL(full ‖ arm) on the same tasks (CPU, 32 continuation rows), for scale:', '',
            '| arm | 5 % | 10 % | 15 % | 20 % |', '|---|---|---|---|---|']
    nk, nn = kl('naive', 0)
    out.append(f'| naive | {nk:.4f} (n {nn}) | | | |')
    for arm in ('chunk_starts', 'query', 'graph', 'hybrid_query'):
        out.append(f'| {arm} | ' + ' | '.join(f'{kl(arm, p)[0]:.4f}' for p in (5, 10, 15, 20)) + ' |')
    out.append('')
    return out


if __name__ == '__main__':
    main()
