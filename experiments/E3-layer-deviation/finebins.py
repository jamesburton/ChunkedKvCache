"""Finer position control for E3 (review fix): role vs Other at the same offset in chunk, with offset bins
1-15 / 16-63 / 64-255 / 256+, from the full raw rows that `ChunkKvLab e3 --raw 1` wrote (the first context of each of the
18 jobs; the committed deviation.csv.gz holds 2 of them). Also prints per-layer extremes behind the README's band averages
(from the committed heatmap.csv and capture-curves.csv).

Usage:  uv run finebins.py <raw dir>   -> finebins.md (this folder)
"""
import csv
import gzip
import math
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = Path(sys.argv[1])
BINS = [("1-15", 1, 16), ("16-63", 16, 64), ("64-255", 64, 256), ("256+", 256, 10**9)]
BANDS = [("1", 1, 2), ("2-3", 2, 4), ("4-11", 4, 12), ("12-23", 12, 24), ("24-35", 24, 36)]
ROLES = ["DefinitionSite", "UseSite", "Import", "Other"]

acc = defaultdict(lambda: [0, 0.0])  # (chunker, role, bin, layer) -> [n, sum combined rel]
contexts = set()
for p in sorted(RAW.glob("*.raw.csv")):
    with open(p, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["chunk"] in ("q", "0") or r["token_role"] not in ROLES:
                continue
            o = int(r["offset"])
            b = next((name for name, lo, hi in BINS if lo <= o < hi), None)
            if b is None:
                continue
            kl, vl, kr, vr = (float(r[k]) for k in ("k_l2", "v_l2", "k_rel", "v_rel"))
            if kr <= 0 or vr <= 0 or math.isinf(kr) or math.isinf(vr):
                continue  # reference norm not recoverable (layer 0 / exact rows)
            kn, vn = kl / kr, vl / vr
            rel = math.hypot(kl, vl) / math.hypot(kn, vn)
            a = acc[(r["chunker"], r["token_role"], b, int(r["layer"]))]
            a[0] += 1
            a[1] += rel
            contexts.add(r["context_id"])

out = [f"# E3 finer position control (generated by finebins.py; do not edit)\n",
       f"{len(contexts)} contexts with full raw rows (the first context of each run job). Cell = mean combined relative "
       "deviation of the role / mean of Other tokens **in the same offset bin**, averaged over the layers of the band "
       "(ratio of band means); n = tokens (per layer).\n"]
for chk in ("symbol", "fixed"):
    out.append(f"\n**{chk}**\n")
    out.append("| role @ offset | n | " + " | ".join(f"layers {b}" for b, _, _ in BANDS) + " | per-layer min-max (1-35) |")
    out.append("|---|---:|" + "---:|" * len(BANDS) + "---|")
    for role in ROLES[:-1]:
        for b, _, _ in BINS:
            n = acc[(chk, role, b, 1)][0]
            if n == 0:
                continue
            cells = []
            for _, lo, hi in BANDS:
                ra = sum(acc[(chk, role, b, l)][1] for l in range(lo, hi)) / max(1, sum(acc[(chk, role, b, l)][0] for l in range(lo, hi)))
                ro = sum(acc[(chk, "Other", b, l)][1] for l in range(lo, hi)) / max(1, sum(acc[(chk, "Other", b, l)][0] for l in range(lo, hi)))
                cells.append(f"{ra / ro:.2f}" if ro else "n/a")
            per = []
            for l in range(1, 36):
                a, o_ = acc[(chk, role, b, l)], acc[(chk, "Other", b, l)]
                if a[0] and o_[0] and o_[1]:
                    per.append((a[1] / a[0]) / (o_[1] / o_[0]))
            out.append(f"| {role} @ {b} | {n} | " + " | ".join(cells) + f" | {min(per):.2f}-{max(per):.2f} |")

# ---- per-layer extremes behind band averages -------------------------------------------------------------------------
heat = {}
for r in csv.DictReader(open(HERE / "heatmap.csv", encoding="utf-8")):
    heat[(r["chunker"], int(r["layer"]), r["group"])] = (float(r["rel"]), float(r["enrichment"]))
stale = defaultdict(lambda: [0.0, 0.0])  # (chunker, layer) -> [n, sum kv_rel] over all stale tokens
with gzip.open(HERE / "deviation-cells.csv.gz", "rt", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r["kind"] == "label" and r["group"] == "stale_all":
            a = stale[(r["chunker"], int(r["layer"]))]
            a[0] += float(r["n"])
            a[1] += float(r["kv_rel"])
cap = defaultdict(dict)
for r in csv.DictReader(open(HERE / "capture-curves.csv", encoding="utf-8")):
    cap[(r["chunker"], r["metric"], float(r["k_pct"]))][int(r["layer"])] = {k: float(r[k]) for k in
        ("share_top", "share_random", "share_position", "share_layer1set")}
out.append("\n## Per-layer extremes (band averages in README/summary.md hide these)\n")
for chk in ("symbol", "fixed"):
    cs = lambda lo, hi: [heat[(chk, l, "ChunkStart")][1] for l in range(lo, hi)]  # noqa: E731
    rel = [stale[(chk, l)][1] / stale[(chk, l)][0] if stale[(chk, l)][0] else float("nan") for l in range(36)]
    out.append(f"- **{chk}**: ChunkStart enrichment layers 1-11 {min(cs(1, 12)):.2f}-{max(cs(1, 12)):.2f}x, layers 12-35 "
               f"{min(cs(12, 36)):.2f}-{max(cs(12, 36)):.2f}x; stale rel layer 1 {rel[1]:.3f}, peak {max(rel[1:]):.3f} "
               f"(layer {rel.index(max(rel[1:]))}) = {max(rel[1:]) / rel[1]:.1f}x layer 1.")
    for met in ("kv_l2", "kv_rel"):
        c = cap[(chk, met, 10.0)]
        top = [c[l]["share_top"] for l in range(1, 36)]
        ratio = [c[l]["share_top"] / c[l]["share_random"] for l in range(1, 36)]
        gap_pos = [(c[l]["share_top"] - c[l]["share_position"], l) for l in range(2, 36)]
        gap_l1 = [(c[l]["share_top"] - c[l]["share_layer1set"], l) for l in range(2, 36)]
        l1_pos = [abs(c[l]["share_layer1set"] - c[l]["share_position"]) for l in range(2, 36)]
        out.append(f"  - {met}, k = 10 %: top-10 % share {min(top):.3f}-{max(top):.3f} ({min(ratio):.1f}-{max(ratio):.1f}x random); "
                   f"best set minus position set up to {max(gap_pos)[0]:.3f} (layer {max(gap_pos)[1]}), minus layer-1 set up to "
                   f"{max(gap_l1)[0]:.3f} (layer {max(gap_l1)[1]}); |layer-1 set - position set| at layers 2-35 max {max(l1_pos):.3f}.")
(HERE / "finebins.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
