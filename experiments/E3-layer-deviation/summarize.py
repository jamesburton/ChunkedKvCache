"""Merge the per-run E3 CSVs written by `ChunkKvLab e3` and summarise them.

Usage:  uv run summarize.py <raw dir>     (writes into this folder)

Writes: contexts.csv, deviation-cells.csv.gz (per context x layer x group sums), capture.csv.gz (per context x layer x metric
x k), deviation.csv.gz (every row of two sampled contexts, the brief's raw columns), heatmap.csv (inputs of plot.py) and
summary.md (tables). Plain Python only.

Conventions (also in README.md):
- "stale" tokens = context tokens outside the first chunk (the first chunk is exact by construction and checked to be 0).
- rel = per-token ||(dK, dV)|| / ||(K, V)_full||, averaged over tokens (mean of ratios). ratio-of-sums is given for K and V
  separately (sum ||dK|| / sum ||K_full||).
- enrichment = group mean rel / mean rel of all stale tokens of the same contexts and layer.
- seed spread: the cell computed per generator seed over the first-N sample contexts only; [min, max] over the 3 seeds.
"""
import csv
import gzip
import io
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = Path(sys.argv[1])
BANDS = [("0", range(0, 1)), ("1", range(1, 2)), ("2-3", range(2, 4)), ("4-11", range(4, 12)), ("12-23", range(12, 24)),
         ("24-35", range(24, 36))]
ROLES = ["ChunkStart", "DefinitionSite", "UseSite", "Import", "Other"]
LABELS = ["cs1", "cs4", "cs16", "def", "def_in_cs16", "def_after_cs16", "use", "import", "cross", "ctxcross", "qtarget"]
NUM = ["n", "k_l2", "v_l2", "kv_l2", "k_rel", "v_rel", "kv_rel", "k_ref", "v_ref"]


def read_all(suffix):
    rows, header = [], None
    for p in sorted(RAW.glob(f"*{suffix}")):
        with open(p, newline="", encoding="utf-8") as f:
            r = csv.reader(f)
            h = next(r)
            header = header or h
            assert h == header, p
            rows.extend(r)
    return header, rows


def write_gz(path, header, rows):
    with gzip.open(path, "wt", newline="", encoding="utf-8", compresslevel=9) as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


# ---- contexts -------------------------------------------------------------------------------------------------------
ch, crow = read_all(".contexts.csv")
contexts = [dict(zip(ch, r)) for r in crow]
with open(HERE / "contexts.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(ch)
    w.writerows(crow)
ctx = {c["context_id"]: c for c in contexts}
CHUNKERS = [c for c in ("symbol", "fixed") if any(x["chunker"] == c for x in contexts)]

# ---- cells ----------------------------------------------------------------------------------------------------------
cellh, cellrows = read_all(".cells.csv")
write_gz(HERE / "deviation-cells.csv.gz", cellh, cellrows)
ci = {k: i for i, k in enumerate(cellh)}
# acc[(context_id, layer, kind, group)] = [n, k_l2, ...]
cells = {}
for r in cellrows:
    cells[(r[ci["context_id"]], int(r[ci["layer"]]), r[ci["kind"]], r[ci["group"]])] = [float(r[ci[k]]) for k in NUM]
LAYERS = 1 + max(k[1] for k in cells)


def pool(ids, layers, kind, group):
    s = [0.0] * len(NUM)
    for cid in ids:
        for l in layers:
            v = cells.get((cid, l, kind, group))
            if v:
                s = [a + b for a, b in zip(s, v)]
    return dict(zip(NUM, s))


def rel(ids, layers, kind, group, metric="kv_rel"):
    p = pool(ids, layers, kind, group)
    return p[metric] / p["n"] if p["n"] else float("nan")


def enrich(ids, layers, kind, group, metric="kv_rel"):
    base = rel(ids, layers, "label", "stale_all", metric)
    return rel(ids, layers, kind, group, metric) / base if base else float("nan")


def sel(**kw):
    return [c["context_id"] for c in contexts if all(c[k] == v for k, v in kw.items())]


def f3(x):
    return "n/a" if x != x else f"{x:.3f}"


def f2(x):
    return "n/a" if x != x else f"{x:.2f}"


def spread(fn, chunker):
    vals = [fn(sel(chunker=chunker, seed=str(s), in_sample="1")) for s in (0, 1, 2)]
    vals = [v for v in vals if v == v]
    return f"[{min(vals):.2f}, {max(vals):.2f}]" if vals else "n/a"


out = io.StringIO()
P = lambda *a: print(*a, file=out)  # noqa: E731

P("# E3 summary (generated by summarize.py; do not edit)\n")
P("## Contexts\n")
P("| corpus | chunker | seed | contexts | in first-N sample | with a kept task | mean tokens | mean chunks | mean query rows | s/context |")
P("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
groups = defaultdict(list)
for c in contexts:
    groups[(c["corpus"], c["chunker"], c["seed"])].append(c)
for (corp, chk, seed), cs in sorted(groups.items()):
    m = lambda k: sum(float(c[k]) for c in cs) / len(cs)  # noqa: E731
    P(f"| {corp} | {chk} | {seed} | {len(cs)} | {sum(c['in_sample'] == '1' for c in cs)} | {sum(c['kept'] == '1' for c in cs)} | "
      f"{m('context_tokens'):.0f} | {m('chunks'):.1f} | {m('query_tokens'):.0f} | {m('seconds'):.1f} |")
P(f"\nTotal {len(contexts)} contexts, {sum(float(c['seconds']) for c in contexts) / 60:.1f} min of context time.\n")

P("## Sanity\n")
c0 = max(float(c["chunk0_max_l2"]) for c in contexts)
l0 = max(float(c["layer0_max_rel"]) for c in contexts)
P(f"- First chunk: max ||(dK, dV)|| over every layer and token of every context = **{c0:g}** (must be exactly 0).")
P(f"- Layer 0 (K/V depend on token and position only; K differs only by RoPE-shift float error): max per-token relative "
  f"deviation over all contexts = {l0:.2e}.")
bad = [c["context_id"] for c in contexts if c["query_map_ok"] != "1"]
P(f"- Query prefix decode round trip failed for {len(bad)} contexts{(': ' + ', '.join(bad)) if bad else ''}.\n")

P("## Token counts by role (stale tokens + query rows, all contexts)\n")
P("| chunker | ChunkStart | DefinitionSite | UseSite | Import | Other | QuerySite | Query | def within first 16 | cross-chunk end | in-context cross | query target |")
P("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for chk in CHUNKERS:
    ids = sel(chunker=chk)
    n = lambda kind, g: int(pool(ids, [0], kind, g)["n"])  # noqa: E731
    P(f"| {chk} | " + " | ".join(str(n("role", r)) for r in ROLES + ["QuerySite", "Query"]) + " | "
      + " | ".join(f"{n('label', g)}" for g in ["def_in_cs16", "cross", "ctxcross", "qtarget"]) + " |")
P("\n(Primary roles count stale tokens only; def within first 16 of `def` = def_in_cs16 / (def_in_cs16 + def_after_cs16).)\n")

# ---- depth profile --------------------------------------------------------------------------------------------------
P("## Depth profile (all stale tokens)\n")
P("rel = mean per-token ||(dK,dV)|| / ||(K,V)_full||; K, V ratio-of-sums = sum ||dX|| / sum ||X_full||; abs = mean ||(dK,dV)||. "
  "Seed spread = [min, max] of rel over generator seeds 0-2 (first-N sample contexts).\n")
P("| layer | symbol rel | symbol seeds | symbol K ros | symbol V ros | symbol abs | fixed rel | fixed seeds | fixed K ros | fixed V ros | fixed abs |")
P("|---:|---:|---|---:|---:|---:|---:|---|---:|---:|---:|")
depth = {}
for l in range(LAYERS):
    row = [str(l)]
    for chk in CHUNKERS:
        ids = sel(chunker=chk)
        p = pool(ids, [l], "label", "stale_all")
        r = p["kv_rel"] / p["n"] if p["n"] else float("nan")
        depth[(chk, l)] = r
        row += [f3(r), spread(lambda i: rel(i, [l], "label", "stale_all"), chk), f3(p["k_l2"] / p["k_ref"] if p["k_ref"] else float("nan")),
                f3(p["v_l2"] / p["v_ref"] if p["v_ref"] else float("nan")), f2(p["kv_l2"] / p["n"] if p["n"] else float("nan"))]
    P("| " + " | ".join(row) + " |")
P()

# ---- roles x layer --------------------------------------------------------------------------------------------------
heat = []
for chk in CHUNKERS:
    ids = sel(chunker=chk)
    P(f"## Roles by layer band, {chk} chunker\n")
    P("Each cell: mean rel, then (enrichment = / all stale tokens) and the enrichment's seed spread.\n")
    P("| role | n tokens | " + " | ".join(f"layers {b}" for b, _ in BANDS) + " |")
    P("|---|---:|" + "---|" * len(BANDS))
    for kind, g in [("role", r) for r in ROLES] + [("label", "stale_all")] + [("label", x) for x in LABELS] + \
            [("role", "QuerySite"), ("role", "Query"), ("label", "query_all")]:
        n = int(pool(ids, [0], kind, g)["n"])
        cellsr = []
        for b, ls in BANDS:
            r = rel(ids, ls, kind, g)
            e = enrich(ids, ls, kind, g)
            cellsr.append(f"{f3(r)} ({f2(e)}x {spread(lambda i: enrich(i, ls, kind, g), chk)})")
        name = g if kind == "role" else f"*{g}*"
        P(f"| {name} | {n} | " + " | ".join(cellsr) + " |")
    P("\n*italic* = multi-label groups (overlap the roles); query rows are not stale tokens and are compared to them only for scale.\n")
    for l in range(LAYERS):
        for kind, g in [("role", r) for r in ROLES + ["QuerySite", "Query"]] + [("label", x) for x in LABELS]:
            heat.append([chk, l, kind, g, rel(ids, [l], kind, g), enrich(ids, [l], kind, g)])

with open(HERE / "heatmap.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["chunker", "layer", "kind", "group", "rel", "enrichment"])
    for h in heat:
        w.writerow(h[:4] + [f"{h[4]:.6g}", f"{h[5]:.6g}"])

# ---- position control -----------------------------------------------------------------------------------------------
P("## Position in chunk (stale tokens)\n")
P("Mean rel by offset-in-chunk bin; and each role's enrichment against **Other tokens in the same offset bin** "
  "(1.00 = no role effect beyond position).\n")
OFF = ["0", "1-3", "4-15", "16-63", "64-255", "256+"]
for chk in CHUNKERS:
    ids = sel(chunker=chk)
    P(f"**{chk}** offset profile\n")
    P("| offset | n | " + " | ".join(f"layers {b}" for b, _ in BANDS) + " |")
    P("|---|---:|" + "---:|" * len(BANDS))
    for o in OFF:
        n = int(pool(ids, [0], "offset", o)["n"])
        P(f"| {o} | {n} | " + " | ".join(f"{f3(rel(ids, ls, 'offset', o))} ({f2(enrich(ids, ls, 'offset', o))}x)" for _, ls in BANDS) + " |")
    P()
    P(f"**{chk}** role vs Other at the same offset (enrichment over Other|bin)\n")
    P("| role @ offset | n | " + " | ".join(f"layers {b}" for b, _ in BANDS) + " |")
    P("|---|---:|" + "---:|" * len(BANDS))
    for r in ["DefinitionSite", "UseSite", "Import"]:
        for b in ["0", "1-15", "16+"]:
            n = int(pool(ids, [0], "role_offset", f"{r}|{b}")["n"])
            cells_ = []
            for _, ls in BANDS:
                a = rel(ids, ls, "role_offset", f"{r}|{b}")
                o = rel(ids, ls, "role_offset", f"Other|{b}")
                cells_.append(f2(a / o) if o and a == a else "n/a")
            P(f"| {r} @ {b} | {n} | " + " | ".join(cells_) + " |")
    P()

# ---- capture --------------------------------------------------------------------------------------------------------
caph, caprows = read_all(".capture.csv")
write_gz(HERE / "capture.csv.gz", caph, caprows)
ki = {k: i for i, k in enumerate(caph)}
cap = defaultdict(list)  # (chunker, metric, k, layer) -> [(context_id, share_top, rnd, pos, overlap, l1)]
for r in caprows:
    cap[(r[ki["chunker"]], r[ki["metric"]], float(r[ki["k_pct"]]), int(r[ki["layer"]]))].append(
        (r[ki["context_id"]], *[float(r[ki[k]]) for k in ["share_top", "share_random", "share_position", "overlap_position", "share_layer1set"]]))


def capmean(chk, metric, k, layers, col, ids=None):
    v = [x[col] for l in layers for x in cap[(chk, metric, k, l)] if ids is None or x[0] in ids]
    v = [a for a in v if a == a]
    return sum(v) / len(v) if v else float("nan")


P("## Concentration: share of a layer's total deviation held by the top-k% stale tokens\n")
P("Per context and layer over the stale tokens, metric ||(dK,dV)|| (abs) and per-token relative (rel). Baselines: random k% "
  "(mean of 20 draws), position = the k% with the smallest offset in chunk (equal chunk prefixes), layer-1 set = the top-k% "
  "at layer 1 (CacheBlend's probe layer) applied to this layer. overlap = |top-k ∩ position set| / k. Mean over contexts; "
  "seed spread of top-k share in brackets.\n")
for metric in ("kv_l2", "kv_rel"):
    for chk in CHUNKERS:
        P(f"**{chk}, {metric}**\n")
        P("| layers | k% | top-k share | seeds | random | position | overlap with position set | layer-1 set |")
        P("|---|---:|---:|---|---:|---:|---:|---:|")
        for b, ls in BANDS[1:]:
            for k in (1.0, 5.0, 10.0, 20.0, 50.0):
                vals = []
                for s in (0, 1, 2):
                    ids = set(sel(chunker=chk, seed=str(s), in_sample="1"))
                    vals.append(capmean(chk, metric, k, ls, 1, ids))
                P(f"| {b} | {k:g} | {f3(capmean(chk, metric, k, ls, 1))} | [{min(vals):.3f}, {max(vals):.3f}] | "
                  f"{f3(capmean(chk, metric, k, ls, 2))} | {f3(capmean(chk, metric, k, ls, 3))} | {f3(capmean(chk, metric, k, ls, 4))} | "
                  f"{f3(capmean(chk, metric, k, ls, 5))} |")
        P()

with open(HERE / "capture-curves.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["chunker", "metric", "layer", "k_pct", "share_top", "share_random", "share_position", "overlap_position", "share_layer1set"])
    for chk in CHUNKERS:
        for metric in ("kv_l2", "kv_rel"):
            for l in range(LAYERS):
                for k in (1.0, 5.0, 10.0, 20.0, 50.0):
                    w.writerow([chk, metric, l, k] + [f"{capmean(chk, metric, k, [l], c):.6g}" for c in range(1, 6)])

# ---- kept vs unfiltered -----------------------------------------------------------------------------------------------
P("## Sensitivity: contexts with a kept Task 8 task vs the unfiltered sample (symbol, seed 0)\n")
kept = sel(chunker="symbol", seed="0", kept="1")
uns = sel(chunker="symbol", seed="0", in_sample="1")
P(f"{len(kept)} kept-task contexts vs {len(uns)} first-N sample contexts (overlap {len(set(kept) & set(uns))}).\n")
P("| group | " + " | ".join(f"kept rel / enr, layers {b}" for b, _ in BANDS[1:]) + " | " + " | ".join(f"sample, layers {b}" for b, _ in BANDS[1:]) + " |")
P("|---|" + "---|" * (2 * (len(BANDS) - 1)))
for kind, g in [("label", "stale_all")] + [("role", r) for r in ROLES] + [("label", "qtarget"), ("label", "query_all")]:
    P(f"| {g} | " + " | ".join(f"{f3(rel(kept, ls, kind, g))} / {f2(enrich(kept, ls, kind, g))}" for _, ls in BANDS[1:]) + " | "
      + " | ".join(f"{f3(rel(uns, ls, kind, g))} / {f2(enrich(uns, ls, kind, g))}" for _, ls in BANDS[1:]) + " |")
P()

# ---- per corpus ---------------------------------------------------------------------------------------------------------
P("## Depth profile per corpus (mean rel of stale tokens)\n")
P("| corpus | chunker | " + " | ".join(f"layers {b}" for b, _ in BANDS) + " |")
P("|---|---|" + "---:|" * len(BANDS))
for corp in ("afclaude", "docagent", "codesharp"):
    for chk in CHUNKERS:
        if not sel(corpus=corp, chunker=chk):
            continue
        ids = sel(corpus=corp, chunker=chk)
        P(f"| {corp} | {chk} | " + " | ".join(f3(rel(ids, ls, "label", "stale_all")) for _, ls in BANDS) + " |")
P()

(HERE / "summary.md").write_text(out.getvalue(), encoding="utf-8")

# ---- sampled raw rows -------------------------------------------------------------------------------------------------
# The brief's deviation.csv columns for two contexts (the first context of afclaude/symbol/s0 and codesharp/fixed/s0),
# plus chunk, offset and the multi-label column.
rawh, rawrows = [], []
for stem, want in [("afclaude-symbol-s0", None), ("codesharp-fixed-s0", None)]:
    p = RAW / f"{stem}.raw.csv"
    if not p.exists():
        continue
    with open(p, newline="", encoding="utf-8") as f:
        r = csv.reader(f)
        rawh = next(r)
        rows = list(r)
    first = rows[0][1]
    rawrows.extend(x for x in rows if x[1] == first)
if rawrows:
    write_gz(HERE / "deviation.csv.gz", rawh, rawrows)
print(f"{len(contexts)} contexts, {len(cellrows)} cell rows, {len(caprows)} capture rows, {len(rawrows)} raw rows -> {HERE}")
